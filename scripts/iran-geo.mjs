// One-off generator: Highcharts/Natural-Earth Iran provinces GeoJSON (pre-projected
// hc units, y grows northward) → compact SVG path strings for the «یک دوست» map UI.
// Usage: node scripts/iran-geo.mjs /tmp/iran-ok.json src/components/shop/occasions/iran-paths.ts
import { readFileSync, writeFileSync } from "fs";

const [, , srcPath, outPath] = process.argv;
const geo = JSON.parse(readFileSync(srcPath, "utf8"));

const FA = {
  Hormozgan: "هرمزگان",
  Bushehr: "بوشهر",
  "Kohgiluyeh and Buyer Ahmad": "کهگیلویه و بویراحمد",
  Fars: "فارس",
  Esfahan: "اصفهان",
  Semnan: "سمنان",
  Golestan: "گلستان",
  Mazandaran: "مازندران",
  Tehran: "تهران",
  Markazi: "مرکزی",
  Yazd: "یزد",
  "Chahar Mahall and Bakhtiari": "چهارمحال و بختیاری",
  Khuzestan: "خوزستان",
  Lorestan: "لرستان",
  Ilam: "ایلام",
  Ardebil: "اردبیل",
  Qom: "قم",
  Hamadan: "همدان",
  Zanjan: "زنجان",
  Qazvin: "قزوین",
  "West Azarbaijan": "آذربایجان غربی",
  "East Azarbaijan": "آذربایجان شرقی",
  Kermanshah: "کرمانشاه",
  Gilan: "گیلان",
  Kordestan: "کردستان",
  "South Khorasan": "خراسان جنوبی",
  "Razavi Khorasan": "خراسان رضوی",
  "North Khorasan": "خراسان شمالی",
  "Sistan and Baluchestan": "سیستان و بلوچستان",
  Kerman: "کرمان",
  Alborz: "البرز",
};

const walk = (a, fn) => {
  if (typeof a[0] === "number") fn(a);
  else for (const c of a) walk(c, fn);
};

// ── global bbox (skip the junk placeholder feature with tiny/fake coords) ──
let minx = Infinity, miny = Infinity, maxx = -Infinity, maxy = -Infinity;
const valid = geo.features.filter((f) => f.properties && FA[f.properties.name]);
for (const f of valid) {
  walk(f.geometry.coordinates, ([x, y]) => {
    if (minx > x) minx = x;
    if (maxx < x) maxx = x;
    if (miny > y) miny = y;
    if (maxy < y) maxy = y;
  });
}
const W = 560;
const scale = W / (maxx - minx);
const H = Math.round((maxy - miny) * scale);
const tx = (x) => +((x - minx) * scale).toFixed(1);
const ty = (y) => +((maxy - y) * scale).toFixed(1); // flip → svg y grows downward

// ── path builder with decimation (in final px space) ──
const EPS = 1.1;
function ringPath(ring) {
  const pts = [];
  for (const [x, y] of ring) {
    const X = tx(x), Y = ty(y);
    const last = pts[pts.length - 1];
    if (!last || Math.hypot(X - last[0], Y - last[1]) >= EPS) pts.push([X, Y]);
  }
  if (pts.length < 3) return "";
  const f = pts[0], l = pts[pts.length - 1];
  if (Math.hypot(f[0] - l[0], f[1] - l[1]) < EPS) pts.pop();
  if (pts.length < 3) return "";
  let d = `M${f[0]} ${f[1]}`;
  for (let i = 1; i < pts.length; i++) d += `L${pts[i][0]} ${pts[i][1]}`;
  return d + "Z";
}

const provinces = [];
for (const f of valid) {
  const en = f.properties.name;
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  const ds = [];
  let bx0 = Infinity, by0 = Infinity, bx1 = -Infinity, by1 = -Infinity;
  for (const poly of polys) {
    for (const ring of poly) {
      for (const [x, y] of ring) {
        const X = tx(x), Y = ty(y);
        if (X < bx0) bx0 = X;
        if (X > bx1) bx1 = X;
        if (Y < by0) by0 = Y;
        if (Y > by1) by1 = Y;
      }
      const d = ringPath(ring);
      if (d) ds.push(d);
    }
  }
  if (!ds.length) continue;
  provinces.push({
    key: en,
    fa: FA[en],
    d: ds.join(""),
    cx: +((bx0 + bx1) / 2).toFixed(1),
    cy: +((by0 + by1) / 2).toFixed(1),
  });
}
provinces.sort((a, b) => a.fa.localeCompare(b.fa, "fa"));

// sanity: Tehran must sit near the top (small y)
const tehran = provinces.find((p) => p.key === "Tehran");
const ys = tehran ? tehran.d.match(/[\d.]+/g).filter((_, i) => i % 2 === 1).map(Number) : [];
console.log("tehran y-range:", Math.min(...ys), "–", Math.max(...ys), "| map H:", H);

const ts = `// ── AUTO-GENERATED by scripts/iran-geo.mjs (source: Natural Earth via Highcharts mapdata) ──
// Do not edit by hand; re-run the script to regenerate.
export interface IranProvinceShape {
  key: string; // english province name (stable id)
  fa: string;  // persian display name
  d: string;   // svg path (${W}×${H} viewBox, y grows downward)
  cx: number;  // bbox center x (برای پین و برچسب)
  cy: number;  // bbox center y
}
export const IRAN_MAP_W = ${W};
export const IRAN_MAP_H = ${H};
export const IRAN_PROVINCES: IranProvinceShape[] = ${JSON.stringify(provinces)};
`;

writeFileSync(outPath, ts, "utf8");
console.log(`provinces=${provinces.length} viewBox=${W}x${H} bytes=${ts.length}`);
