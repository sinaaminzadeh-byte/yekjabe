async function main() {
  for (const p of POSTS) {
    const words = p.content.trim().split(/\s+/).length;
    if (words < 250 || words > 400) throw new Error(`post ${p.slug} word count ${words} outside 250-400`);
    if (p.excerpt.length > 160) throw new Error(`post ${p.slug} excerpt too long`);
    await db.post.upsert({
      where: { slug: p.slug },
      create: { ...p, published: true, publishedAt: new Date(), authorId: "seed" },
      update: { title: p.title, excerpt: p.excerpt, tags: p.tags, content: p.content, published: true },
    });
  }
  for (const e of EXPERIENCES) {
    const existing = await db.experience.findFirst({ where: { name: e.name, city: e.city, status: "published" }, select: { id: true } });
    if (existing) {
      await db.experience.update({ where: { id: existing.id }, data: { body: e.body, occasion: e.occasion, consent: true } });
    } else {
      await db.experience.create({ data: { ...e, consent: true, status: "published", publishedAt: new Date() } });
    }
  }
  const posts = await db.post.count();
  const experiences = await db.experience.count();
  console.log(`seed-blog ✓ posts:${posts} experiences:${experiences}`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => db.$disconnect());
