async function main() {
  for (const p of POSTS) {
    const words = p.content.trim().split(/\s+/).length;
    if (words < 350 || words > 500) throw new Error(`post ${p.slug} word count ${words} outside 350-500`);
    if (p.excerpt.length > 160) throw new Error(`post ${p.slug} excerpt too long`);
    if (p.metaTitle.length > 60) throw new Error(`post ${p.slug} metaTitle too long`);
    const mdLen = p.metaDescription.length;
    if (mdLen < 70 || mdLen > 160) throw new Error(`post ${p.slug} metaDescription ${mdLen} outside 70-160`);
    for (const style of ["## ", "### ", ":::quote", ":::info", ":::tip", ":::love", ":::warn", "![", "\n---\n", "- ", "**", "/product?slug=bear", "/pick"]) {
      if (!p.content.includes(style)) throw new Error(`post ${p.slug} missing style ${style}`);
    }
    await db.post.upsert({
      where: { slug: p.slug },
      create: {
        ...p,
        published: true,
        publishedAt: new Date(),
        authorId: "seed",
      },
      update: {
        title: p.title,
        excerpt: p.excerpt,
        tags: p.tags,
        content: p.content,
        coverKey: p.coverKey,
        metaTitle: p.metaTitle,
        metaDescription: p.metaDescription,
        published: true, // publishedAt preserved — never reset on reseed
      },
    });
  }
  for (const e of EXPERIENCES) {
    const existing = await db.experience.findFirst({ where: { name: e.name, city: e.city, status: "published" }, select: { id: true } });
    if (existing) {
      await db.experience.update({ where: { id: existing.id }, data: { body: e.body, occasion: e.occasion, consent: true } });
    } else {
      await db.experience.create({ data: { ...e, consent: true, status: "published", publishedAt: new Date() } });
    }
  }
  const posts = await db.post.count();
  const experiences = await db.experience.count();
  console.log(`seed-blog ✓ posts:${posts} experiences:${experiences}`);
}

main()
