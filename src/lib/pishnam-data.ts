export function plushLabel(kind: PlushKind): string {
  const species: Record<PlushKind, string> = {
    bear: "خرس",
    bunny: "خرگوش",
    cat: "گربه",
    panda: "پاندا",
    sheep: "گوسفند",
    duck: "اردک",
  };
  return `${PLUSH_MAP[kind].name}، ${species[kind]}`;
}

