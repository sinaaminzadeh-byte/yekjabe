export const PRODUCT_SEO_MAP: Record<PlushKind, ProductSeo> = Object.fromEntries(
  PRODUCT_SEO.map((p) => [p.slug, p]),
) as Record<PlushKind, ProductSeo>;

export function isPlushKind(slug: string): slug is PlushKind {
  return slug in PRODUCT_SEO_MAP;
}

/** Safe lookup for hash-router query strings — returns null on unknown/empty. */
export function getProductSeo(slug: string | null | undefined): ProductSeo | null {
  if (!slug) return null;
  return isPlushKind(slug) ? PRODUCT_SEO_MAP[slug] : null;
}
